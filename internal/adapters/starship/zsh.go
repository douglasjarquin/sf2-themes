package starship

import (
	"strings"

	"github.com/douglasjarquin/sf2-themes/v2/internal/catalog"
	"github.com/douglasjarquin/sf2-themes/v2/internal/plan"
	"github.com/douglasjarquin/sf2-themes/v2/internal/pycompat"
)

const sourceHint = `[[ -f "$HOME/.config/sf2-theme/zsh-syntax-highlighting.zsh" ]] && ` +
	`source "$HOME/.config/sf2-theme/zsh-syntax-highlighting.zsh"`

func highlightPath() (string, error) {
	root, err := configRoot()
	return pycompat.Path(root, "sf2-theme", "zsh-syntax-highlighting.zsh"), err
}

// renderHighlight renders a sourcable zsh snippet that retints command highlights.
//
// The stock highlighter paints commands ANSI green. The command family is remapped to accent so typed commands track
// character identity with the Starship dirname.
func renderHighlight(theme catalog.Theme) string {
	accent := string(theme.UI.Accent)
	secondary := string(theme.UI.AccentSecondary)
	muted := string(theme.UI.Muted)
	red := string(theme.Semantic.Red)
	return strings.Join([]string{
		"# sf2-themes: " + theme.Metadata.SelectableID(),
		"# Generated by sf2-themes. Source after zsh-syntax-highlighting.zsh.",
		"typeset -gA ZSH_HIGHLIGHT_STYLES",
		"ZSH_HIGHLIGHT_STYLES[command]='fg=" + accent + "'",
		"ZSH_HIGHLIGHT_STYLES[arg0]='fg=" + accent + "'",
		"ZSH_HIGHLIGHT_STYLES[builtin]='fg=" + accent + "'",
		"ZSH_HIGHLIGHT_STYLES[precommand]='fg=" + secondary + ",underline'",
		"ZSH_HIGHLIGHT_STYLES[suffix-alias]='fg=" + secondary + ",underline'",
		"ZSH_HIGHLIGHT_STYLES[autodirectory]='fg=" + secondary + ",underline'",
		"ZSH_HIGHLIGHT_STYLES[single-hyphen-option]='fg=" + muted + "'",
		"ZSH_HIGHLIGHT_STYLES[double-hyphen-option]='fg=" + muted + "'",
		"ZSH_HIGHLIGHT_STYLES[unknown-token]='fg=" + red + ",bold'",
		"",
	}, "\n")
}

func planZshSyntax(theme catalog.Theme) (plan.Step, error) {
	path, err := highlightPath()
	if err != nil {
		return plan.Step{}, err
	}
	return plan.Write(path, renderHighlight(theme)), nil
}
